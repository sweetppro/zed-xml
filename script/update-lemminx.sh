#!/usr/bin/env sh
# Pins the extension to a release of redhat-developer/vscode-xml, which publishes the native
# LemMinX binaries, and records the SHA-256 that Red Hat publishes for each one.
#
# Usage: script/update-lemminx.sh <vscode-xml release tag, e.g. 0.29.3>
set -eu

tag="${1:?usage: $0 <vscode-xml release tag>}"
base="https://github.com/redhat-developer/vscode-xml/releases/download/$tag"
out="$(dirname "$0")/../src/lemminx_release.rs"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
    echo "// Generated by script/update-lemminx.sh. Do not edit."
    echo ""
    echo "/// The release of redhat-developer/vscode-xml the LemMinX binary is downloaded from."
    echo "pub const TAG: &str = \"$tag\";"
    echo ""
    echo "/// SHA-256 of each executable, as published next to its zip in the release."
    echo "pub const SHA256: &[(&str, &str)] = &["
    for asset in lemminx-win32 lemminx-osx-x86_64 lemminx-osx-aarch_64 lemminx-linux-x86_64 lemminx-linux-aarch_64; do
        # Each file reads "<hash>  <executable>".
        hash="$(curl -fsSL "$base/$asset.sha256" | cut -d ' ' -f 1)"
        case "$hash" in
            *[!0-9a-f]* | "") echo "bad checksum for $asset: '$hash'" >&2; exit 1 ;;
        esac
        [ "${#hash}" -eq 64 ] || { echo "bad checksum for $asset: '$hash'" >&2; exit 1; }
        printf '    (\n        "%s",\n        "%s",\n    ),\n' "$asset" "$hash"
    done
    echo "];"
} > "$tmp"

mv "$tmp" "$out"
trap - EXIT
echo "Pinned vscode-xml $tag in $out"
